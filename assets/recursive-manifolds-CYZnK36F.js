   <section class='publication-abstract'><h2 class='publication-abstract-heading'>Abstract</h2><div class='publication-abstract-body'>Many real-world distributions are organized at more than one resolution. A
coarse conditional law captures structure shared by its descendants;
conditioning more finely reveals additional variation, while the resulting laws
remain related through their common parent. We call this the <span class='pplri7t-x-x-109'>recursive manifold
hypothesis</span>. We formalize the hypothesis as multiscale conditional refinement of
probability laws across successive coarse-to-fine relations. The energy
distance metric between probability distributions compares the laws
model-independently and allows us to decompose their variation exactly. Each
parent–child relation has three coordinates: absolute law variation <span class='mathjax-inline'>\\(V\\)</span>, the fraction <span class='mathjax-inline'>\\(F\\)</span>
revealed by the children, and parent organization <span class='mathjax-inline'>\\(A\\)</span> relative to the expected
organization of a random parent map with the same group sizes. The product <span class='mathjax-inline'>\\(R=FA\\)</span>
yields a sufficient population criterion for one specified parent–child relation.
We estimate this profile from pooled energy-distance U-statistics and
quantify uncertainty in <span class='mathjax-inline'>\\(R\\)</span> by an observation jackknife. Experiments center on
ImageNet-1k and Amazon Reviews 2023 and include pushforward laws
from DINOv2-L and Qwen3-Embedding-4B. Across image, text, and
spiking-speech datasets, 13 of 14 relation–representation pairs reveal
additional variation that the supplied parent organizes better than a
random map with the same group sizes. ImageNet-1k, Amazon Reviews,
FGVC-Aircraft, and ImageNet-R satisfy the criterion on two successive
relations. Spiking Heidelberg Digits distinguishes structural strength across
attributes: speakers are strongly organized within words, whereas the
language attribute provides little organization of word laws. Excluding
singleton branches preserves these empirical findings. These results suggest
objectives and models that respect the hierarchical organization in data
laws.</div></section>
